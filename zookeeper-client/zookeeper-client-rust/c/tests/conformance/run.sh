# Differential conformance test runner.
#
# Compiles each conformance test scenario once against the public C headers,
# links it against the reference legacy library, and executes the identical
# binary against both the legacy C and Rust drop-in cores by configuring the
# dynamic loader search path (`DYLD_LIBRARY_PATH` on macOS, `LD_LIBRARY_PATH` on
# Linux). The trace recorder verifies at startup that the loaded shared library
# resides in the expected directory. Each run starts isolated ZooKeeper server
# instances, normalizes the resulting execution trace and log streams, and
# compares the two runs under the comparison mode declared by the test scenario.
#
# Usage: run.sh --rust LIBDIR [--legacy LIBDIR] [--flavor mt|st] [--out DIR]
#               [--port-base N] [--reps N] [--sasl] [--tls DIR] [CASE...]
#
#   --rust       directory containing the Rust drop-in `libzookeeper_FL.2.dylib`
#                (macOS) or `libzookeeper_FL.so.2` (Linux)
#   --legacy     directory containing the reference legacy library
#                (default: /tmp/zk-legacy-ref/install-plain/lib)
#   --flavor     library flavor `FL` (default: mt). single threaded (`st`) builds
#                omit `-DTHREADED` and link against `libzookeeper_st`.
#   --out        working and output directory (default: /tmp/zkconf, or
#                /tmp/zkconf-st for st)
#   --port-base  starting port for the 12-port server allocation block
#                (default: 22750)
#   --reps       repetitions per core (default: 1; full verification uses 3)
#   --sasl       configure servers with a JAAS `Server` section defining the
#                DIGEST-MD5 principal `myuser` / `mypassword`, and export
#                `ZKCONF_SASL=1` to scenarios (`sasl_glue`). Requires `sasl` or
#                `full` library builds for both cores.
#   --tls DIR    configure servers with `secureClientPort` (`port + 6`),
#                `NettyServerCnxnFactory`, and keystores from `DIR` (generated by
#                `ssl/gencerts.sh`). `ZKCONF_TLS_CLIENT_AUTH` controls
#                `ssl.clientAuth` (default: `want`). Exports `ZKCONF_TLS_HOSTS`
#                and `ZKCONF_TLS_DIR` to scenarios, shifts dead ports to
#                `BASE+12..BASE+13`, and reserves `BASE+14..BASE+19` for the
#                OpenSSL test peers of `ldg_c_tls_openssl` (20 ports total).
#                Requires `ssl` or `full` library builds for both cores.
#   CASE         scenario names to execute (default: all `cases/*.c` and `*.cc`)
#
# Scenario flavor directives: a comment line containing `zkconf-flavors: mt st`
# declares supported library flavors (default: `mt` only). A comment line
# `zkconf-skip-st: REASON` documents why a scenario is excluded from `st` runs.
# Scenarios incompatible with the active flavor are reported as `SKIP` without
# failing the run.
#
# Preload directives: `zkconf-preload: connect` injects `lib/zkconf_preload.c`
# via `DYLD_INSERT_LIBRARIES` / `LD_PRELOAD` to interpose `connect(2)` across
# both cores. `zkconf-preload: sasl` injects `lib/zkconf_sasl_preload.c` linked
# against Cyrus SASL from `ZKCONF_SASL_PREFIX` (default: Homebrew `cyrus-sasl`
# on macOS, `/usr` on Linux) to trace Cyrus SASL and socket lifecycle ordering.
#
# C++ exception scenarios (`cases/NAME.cc`) compile with `-fexceptions` to verify
# callback exception propagation while linking the C trace recorder.
#
# Comparison modes:
#   EXACT     normalized event traces must match line-for-line
#   PER-ROLE  normalized event traces must match per thread role subsequence
#   DEV       no cross-core trace diff; each core validates its own assertions
# Scenarios with nondeterministic outcome sets encode the valid set directly in
# the trace and run under `EXACT`.
# Log comparison modes:
#   ordered   `INFO`+ lines ordered per thread role; `DEBUG` lines as a multiset
#   set       all log lines compared as a multiset
#   uniq      distinct `INFO`+ lines compared as a set (for retry-loop scenarios)
#   ignore    log output is not diffed across cores
# Every execution must exit 0 with zero harness errors and zero failed `DEV`
# assertions. Characterized upstream failures (`KNOWN ... XFAIL:` in `.dev`) do
# not fail the scenario and are summarized as `xfail-CORE=N`.

set -uo pipefail

# Resolve repository paths: RCDIR is the Rust C compatibility root, RDIR is the
# Rust workspace root, and CDIR is the legacy C client tree (overridable via
# ZK_C_DIR).
HERE="$(cd "$(dirname "$0")" && pwd)"
RCDIR="$(cd "$HERE/../.." && pwd)"
RDIR="$(cd "$RCDIR/.." && pwd)"
CDIR="$(cd "${ZK_C_DIR:-$RDIR/../zookeeper-client-c}" && pwd)"
# `ZKCONF_SERVER` overrides the server lifecycle script path.
SERVER="${ZKCONF_SERVER:-$RDIR/dev/test-server.sh}"
LEGACY=/tmp/zk-legacy-ref/install-plain/lib
RUST=""
OUT=""
FL=mt
BASE=22750
REPS=1
SASL=0
TLS=""
CASES=()
CASE_TIMEOUT="${ZKCONF_CASE_TIMEOUT:-180}"

while [ $# -gt 0 ]; do
    case "$1" in
    --rust) RUST="$2"; shift 2 ;;
    --legacy) LEGACY="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    --flavor) FL="$2"; shift 2 ;;
    --port-base) BASE="$2"; shift 2 ;;
    --reps) REPS="$2"; shift 2 ;;
    --sasl) SASL=1; shift ;;
    --tls) TLS="$2"; shift 2 ;;
    -h|--help)
        sed -n '/^# Differential conformance test runner\./,/^# not fail the scenario/p' "$0"
        exit 0 ;;
    *) CASES+=("$1"); shift ;;
    esac
done

if [ -z "$RUST" ]; then
    echo "run.sh: --rust LIBDIR is required" >&2
    exit 2
fi
case "$FL" in
mt) OUT="${OUT:-/tmp/zkconf}" ;;
st) OUT="${OUT:-/tmp/zkconf-st}" ;;
*) echo "run.sh: --flavor must be mt or st" >&2; exit 2 ;;
esac
# Platform-specific shared library names, dynamic loader environment variables,
# and preload link flags (`-ldl` is linked on Linux for `dlsym`/`dladdr` on
# glibc < 2.34).
if [ "$(uname -s)" = Darwin ]; then
    LIBFILE="libzookeeper_$FL.2.dylib"
    LIBPATH_VAR=DYLD_LIBRARY_PATH
    PRELOAD_VAR=DYLD_INSERT_LIBRARIES
    SHLIB_EXT=dylib
    SHLIB_FLAGS=(-dynamiclib)
    SHLIB_LIBS=()
    DEFAULT_SASL_PREFIX=/opt/homebrew/opt/cyrus-sasl
    DEFAULT_OPENSSL=/opt/homebrew/opt/openssl@3/bin/openssl
else
    LIBFILE="libzookeeper_$FL.so.2"
    LIBPATH_VAR=LD_LIBRARY_PATH
    PRELOAD_VAR=LD_PRELOAD
    SHLIB_EXT=so
    SHLIB_FLAGS=(-shared -fPIC -D_GNU_SOURCE)
    SHLIB_LIBS=(-ldl)
    DEFAULT_SASL_PREFIX=/usr
    DEFAULT_OPENSSL=openssl
fi
for d in "$LEGACY" "$RUST"; do
    if [ ! -f "$d/$LIBFILE" ]; then
        echo "run.sh: no $LIBFILE in $d" >&2
        exit 2
    fi
done
LEGACY="$(cd "$LEGACY" && pwd)"
RUST="$(cd "$RUST" && pwd)"
mkdir -p "$OUT/bin"
OUT="$(cd "$OUT" && pwd)"

# Configure server side DIGEST-MD5 SASL authentication via JAAS and JVM flags
# (`zookeeper.fips-mode=false` is required for DIGEST-MD5 support in ZooKeeper).
if [ "$SASL" = 1 ]; then
    cat >"$OUT/jaas.conf" <<'JAAS'
Server {
    org.apache.zookeeper.server.auth.DigestLoginModule required
    user_myuser="mypassword";
};
JAAS
    ZK_TEST_SERVER_JVM_OPTS="${ZK_TEST_SERVER_JVM_OPTS:-} \
-Djava.security.auth.login.config=$OUT/jaas.conf \
-Dzookeeper.authProvider.1=org.apache.zookeeper.server.auth.SASLAuthenticationProvider \
-Dzookeeper.fips-mode=false"
    export ZK_TEST_SERVER_JVM_OPTS
    export ZKCONF_SASL=1
fi

# Configure server side Netty TLS listeners using `gencerts.sh` JKS keystores.
if [ -n "$TLS" ]; then
    if [ ! -f "$TLS/server.jks" ] || [ ! -f "$TLS/servertrust.jks" ]; then
        echo "run.sh: --tls $TLS has no server.jks and servertrust.jks" >&2
        exit 2
    fi
    TLS="$(cd "$TLS" && pwd)"
    export ZKCONF_TLS_DIR="$TLS"
fi
# Emits `zoo.cfg` properties for a server listening on plaintext port `$1`,
# prepending any caller supplied `ZK_TEST_SERVER_PROPS`.
server_props() {
    [ -z "${ZK_TEST_SERVER_PROPS:-}" ] || printf '%s\n' "$ZK_TEST_SERVER_PROPS"
    [ -n "$TLS" ] || return 0
    printf '%s\n' "secureClientPort=$(($1 + 6))" \
        "serverCnxnFactory=org.apache.zookeeper.server.NettyServerCnxnFactory" \
        "ssl.clientAuth=${ZKCONF_TLS_CLIENT_AUTH:-want}" \
        "ssl.keyStore.location=$TLS/server.jks" "ssl.keyStore.password=password" \
        "ssl.trustStore.location=$TLS/servertrust.jks" "ssl.trustStore.password=password"
}

if [ ${#CASES[@]} -eq 0 ]; then
    for f in "$HERE"/cases/*.c "$HERE"/cases/*.cc; do
        [ -f "$f" ] || continue
        f="$(basename "$f")"
        CASES+=("${f%.*}")
    done
fi

# Port layout: legacy runs allocate `BASE..BASE+2`, Rust runs allocate
# `BASE+3..BASE+5`, and unbound dead endpoints default to `BASE+10..BASE+11`
# (`BASE+12..BASE+13` when `--tls` is active, or `BASE+$ZKCONF_DEAD_OFFSET`).
if [ -n "$TLS" ]; then DEAD_OFF="${ZKCONF_DEAD_OFFSET:-12}"; else
    DEAD_OFF="${ZKCONF_DEAD_OFFSET:-10}"; fi
ports_for() {
    if [ "$1" = c ]; then echo "$BASE $((BASE + 1)) $((BASE + 2))"; else
        echo "$((BASE + 3)) $((BASE + 4)) $((BASE + 5))"; fi
}
dead_for() {
    if [ "$1" = c ]; then echo $((BASE + DEAD_OFF)); else echo $((BASE + DEAD_OFF + 1)); fi
}

STARTED=()
stop_all() {
    local entry
    for entry in "${STARTED[@]+"${STARTED[@]}"}"; do
        "$SERVER" stop "${entry%%@*}" "${entry#*@}" >/dev/null 2>&1 || true
    done
    STARTED=()
}
trap stop_all EXIT INT TERM

# Resolves the source file path (`cases/NAME.c` or `cases/NAME.cc`) for a scenario.
case_src() {
    if [ -f "$HERE/cases/$1.cc" ]; then echo "$HERE/cases/$1.cc"; else
        echo "$HERE/cases/$1.c"; fi
}
# Extracts supported flavors from the scenario's `zkconf-flavors:` directive (default: `mt`).
case_flavors() {
    local line
    line="$(grep -m1 'zkconf-flavors:' "$(case_src "$1")" 2>/dev/null)"
    if [ -z "$line" ]; then echo mt; else echo "${line#*zkconf-flavors:}"; fi
}
skip_reason() {
    local line
    if [ "$FL" = st ]; then
        line="$(grep -m1 'zkconf-skip-st:' "$(case_src "$1")" 2>/dev/null)"
        if [ -n "$line" ]; then
            echo "${line#*zkconf-skip-st: }" | sed -E 's/ *\*\/$//'
        else
            echo "the case uses the mt-only sync API or library threads"
        fi
    else
        echo "an st-only case"
    fi
}
RUN_CASES=()
SKIPPED=()
for c in "${CASES[@]}"; do
    if [ ! -f "$(case_src "$c")" ]; then
        echo "run.sh: no case $c" >&2
        exit 2
    fi
    if [[ " $(case_flavors "$c") " == *" $FL "* ]]; then
        RUN_CASES+=("$c")
    else
        SKIPPED+=("$c")
    fi
done

# Ensure the `zk-testkit` TLS certificate corpus exists, generating it on demand
# via `cargo run -p zk-testkit --bin zk-fixtures -- tls` unless
# `ZK_TEST_TLS_FIXTURES` specifies a pre-generated directory.
if [ -n "${ZK_TEST_TLS_FIXTURES:-}" ]; then
    FIX="$ZK_TEST_TLS_FIXTURES"
elif command -v cargo >/dev/null 2>&1; then
    FIX="$(cd "$RDIR" && \
        ZK_TEST_OPENSSL="${ZK_TEST_OPENSSL:-${OPENSSL:-$DEFAULT_OPENSSL}}" \
        cargo run -q --locked --offline -p zk-testkit --bin zk-fixtures -- tls)" || {
        echo "run.sh: zk-fixtures failed to generate TLS fixtures" >&2
        exit 2
    }
else
    echo "run.sh: TLS fixtures require cargo; install cargo or set ZK_TEST_TLS_FIXTURES=DIR" >&2
    exit 2
fi
if [ ! -f "$FIX/ca.pem" ]; then
    echo "run.sh: TLS fixture directory $FIX is missing ca.pem" >&2
    exit 2
fi
# Normalize to an absolute path before passing as a C string literal macro.
FIX="$(cd "$FIX" && pwd)"

# 1. Compile all active scenarios once against the public C headers.
# `-DTHREADED` is defined only for `mt` builds; `-lpthread` is linked in both
# flavors because the harness trace recorder and in-process proxies use pthreads.
CFLAGS=(-std=c99 -Wall -Wextra -Werror -g -O1 -D_GNU_SOURCE
    -I"$CDIR/include" -I"$CDIR/generated" -I"$HERE/lib"
    "-DZKCONF_C_DIR=\"$CDIR\""
    "-DZKCONF_TLS_FIX=\"$FIX\"")
if [ "$FL" = mt ]; then
    CFLAGS+=(-DTHREADED)
fi
LIBOBJS=("$OUT/bin/zkconf.o" "$OUT/bin/zkconf_sync.o" "$OUT/bin/zkconf_tls.o")
PRELOAD="$OUT/bin/libzkconf_preload.$SHLIB_EXT"
if ! cc -std=c99 -Wall -Wextra -Werror -g -O1 "${SHLIB_FLAGS[@]}" -I"$HERE/lib" \
    "$HERE/lib/zkconf_preload.c" ${SHLIB_LIBS[@]+"${SHLIB_LIBS[@]}"} -o "$PRELOAD"; then
    echo "run.sh: build of lib/zkconf_preload.c failed" >&2
    exit 2
fi
# Build the SASL preload library linked against `libsasl2` when required by any active case.
SASL_PRELOAD="$OUT/bin/libzkconf_sasl_preload.$SHLIB_EXT"
SASL_PREFIX="${ZKCONF_SASL_PREFIX:-$DEFAULT_SASL_PREFIX}"
for c in "${RUN_CASES[@]+"${RUN_CASES[@]}"}"; do
    if grep -q 'zkconf-preload: sasl' "$(case_src "$c")"; then
        if ! cc -std=c99 -Wall -Wextra -Werror -g -O1 "${SHLIB_FLAGS[@]}" -I"$HERE/lib" \
            -I"$SASL_PREFIX/include" "$HERE/lib/zkconf_sasl_preload.c" \
            -L"$SASL_PREFIX/lib" -lsasl2 ${SHLIB_LIBS[@]+"${SHLIB_LIBS[@]}"} \
            -o "$SASL_PRELOAD"; then
            echo "run.sh: build of lib/zkconf_sasl_preload.c failed" >&2
            exit 2
        fi
        break
    fi
done
for f in zkconf zkconf_sync zkconf_tls; do
    if ! cc "${CFLAGS[@]}" -c "$HERE/lib/$f.c" -o "$OUT/bin/$f.o"; then
        echo "run.sh: compile of lib/$f.c failed" >&2
        exit 2
    fi
done
CXXFLAGS=(-std=c++11 -fexceptions -Wall -Wextra -Werror -g -O1
    "${CFLAGS[@]:6}")
for c in "${RUN_CASES[@]+"${RUN_CASES[@]}"}"; do
    src="$(case_src "$c")"
    if [ "${src##*.}" = cc ]; then
        c++ "${CXXFLAGS[@]}" "$src" "${LIBOBJS[@]}" \
            -L"$LEGACY" -lzookeeper_"$FL" -lpthread ${SHLIB_LIBS[@]+"${SHLIB_LIBS[@]}"} \
            -o "$OUT/bin/$c"
    else
        cc "${CFLAGS[@]}" "$src" "${LIBOBJS[@]}" \
            -L"$LEGACY" -lzookeeper_"$FL" -lpthread ${SHLIB_LIBS[@]+"${SHLIB_LIBS[@]}"} \
            -o "$OUT/bin/$c"
    fi || {
        echo "run.sh: compile of $c failed" >&2
        exit 2
    }
done

# 2. Execute a single scenario repetition against one core with fresh servers.
run_one() {
    local c="$1" core="$2" rep="$3" nserv="$4"
    local libdir dir ports dead i p hosts tlshosts portmap rc pid preload
    if [ "$core" = c ]; then libdir="$LEGACY"; else libdir="$RUST"; fi
    dir="$OUT/$c/$core.$rep"
    rm -rf "$dir"
    mkdir -p "$dir"
    read -r -a ports <<<"$(ports_for "$core")"
    dead="$(dead_for "$core")"
    hosts=""
    tlshosts=""
    portmap="$dead=PD"
    for i in 0 1 2; do
        p="${ports[$i]}"
        portmap="$portmap,$p=P$((i + 1))"
        hosts="${hosts:+$hosts,}127.0.0.1:$p"
        if [ -n "$TLS" ]; then
            portmap="$portmap,$((p + 6))=T$((i + 1))"
            tlshosts="${tlshosts:+$tlshosts,}127.0.0.1:$((p + 6))"
        fi
    done
    {
        echo '#!/bin/sh'
        echo "case \"\$2\" in"
        echo "    0) P=${ports[0]};; 1) P=${ports[1]};; 2) P=${ports[2]};; *) exit 2;;"
        echo "esac"
        echo "ZK_TEST_SERVER_PROPS=\"\$(cat '$dir/props'\"\$2\")\""
        echo "export ZK_TEST_SERVER_PROPS"
        echo "exec '$SERVER' \"\$1\" \"\$P\" '$dir/srv'\"\$2\""
    } >"$dir/ctl.sh"
    chmod +x "$dir/ctl.sh"
    for i in 0 1 2; do
        server_props "${ports[$i]}" >"$dir/props$i"
    done
    preload=""
    if grep -q 'zkconf-preload: connect' "$(case_src "$c")"; then
        preload="$PRELOAD"
    elif grep -q 'zkconf-preload: sasl' "$(case_src "$c")"; then
        preload="$SASL_PRELOAD"
    fi
    for ((i = 0; i < nserv; i++)); do
        ZK_TEST_SERVER_PROPS="$(cat "$dir/props$i")" \
            "$SERVER" start "${ports[$i]}" "$dir/srv$i" >"$dir/server$i.start" 2>&1 || {
            echo "run.sh: server start failed: $c $core port ${ports[$i]}" >&2
            return 1
        }
    done
    env "$LIBPATH_VAR=$libdir" ZKCONF_LIBDIR="$libdir" ZKCONF_CORE="$core" \
        ZKCONF_OUT="$dir/out" ZKCONF_HOSTS="$hosts" ZKCONF_DEAD="127.0.0.1:$dead" \
        ZKCONF_PORTS="$portmap" ZKCONF_CTL="$dir/ctl.sh" TZ=UTC LC_ALL=C \
        ZKCONF_TLS_HOSTS="$tlshosts" ${preload:+"$PRELOAD_VAR=$preload"} \
        "$OUT/bin/$c" >"$dir/stdout" 2>"$dir/stderr" &
    pid=$!
    # Run an isolated watchdog timer that closes inherited descriptors and kills
    # the test process if `CASE_TIMEOUT` expires.
    (
        exec >/dev/null 2>&1
        sleep "$CASE_TIMEOUT" &
        s=$!
        trap 'kill "$s"; exit 0' TERM
        wait "$s"
        kill -9 "$pid"
    ) &
    local watchdog=$!
    wait "$pid"
    rc=$?
    kill "$watchdog" 2>/dev/null
    wait "$watchdog" 2>/dev/null
    echo "$rc" >"$dir/exit"
    for ((i = 0; i < 3; i++)); do
        "$SERVER" stop "${ports[$i]}" "$dir/srv$i" >/dev/null 2>&1 || true
    done
    return 0
}

# Formats trace and log files according to the scenario's comparison mode.
view_trace() {
    local mode="$1" f="$2"
    if [ ! -f "$f" ]; then echo "<missing>"; return; fi
    if [ "$mode" = PER-ROLE ]; then
        grep -v '^#' "$f" | sort -s -k1,1
    else
        grep -v '^#' "$f"
    fi
}
# Normalize wall-clock timeout overshoot deltas in log messages before diffing.
log_norm() {
    sed -E -e 's/exceeded timeout by -?[0-9]+ms/exceeded timeout by Nms/' \
        -e 's/Exceeded deadline by -?[0-9]+ms/Exceeded deadline by Nms/' "$1"
}
view_log() {
    local mode="$1" f="$2"
    if [ ! -f "$f" ]; then echo "<missing>"; return; fi
    case "$mode" in
    ordered)
        log_norm "$f" | grep -v ' ZOO_DEBUG@' | sort -s -k1,1
        echo "--- debug multiset"
        log_norm "$f" | grep ' ZOO_DEBUG@' | sed -E 's/xid=-?[0-9a-fx]+/xid=X/g' | sort
        ;;
    set) log_norm "$f" | sort ;;
    uniq) log_norm "$f" | grep -v ' ZOO_DEBUG@' | sort -u ;;
    *) : ;;
    esac
}

# 3. Execute scenarios and compare outputs across cores.
FAILED=0
SUMMARY="$OUT/summary.txt"
: >"$SUMMARY"
echo "run.sh: flavor $FL" | tee -a "$SUMMARY"
for c in "${SKIPPED[@]+"${SKIPPED[@]}"}"; do
    printf '%-24s %-8s %-8s SKIP (%s)\n' "$c" - - "$(skip_reason "$c")" | tee -a "$SUMMARY"
done
for c in "${RUN_CASES[@]+"${RUN_CASES[@]}"}"; do
    # Supply `LIBPATH_VAR=$LEGACY` when querying `--describe` since ELF test
    # binaries omit an embedded rpath.
    desc="$(env "$LIBPATH_VAR=$LEGACY" "$OUT/bin/$c" --describe)"
    nserv="$(sed -E 's/.*servers=([0-9]+).*/\1/' <<<"$desc")"
    mode="$(sed -E 's/.*mode=([A-Z-]+).*/\1/' <<<"$desc")"
    lmode="$(sed -E 's/.*log=([a-z]+).*/\1/' <<<"$desc")"
    verdict=PASS
    notes=""
    for ((r = 1; r <= REPS; r++)); do
        run_one "$c" c "$r" "$nserv" &
        p1=$!
        run_one "$c" rust "$r" "$nserv" &
        p2=$!
        wait $p1 || { verdict=FAIL; notes="$notes server-c"; }
        wait $p2 || { verdict=FAIL; notes="$notes server-rust"; }
        for core in c rust; do
            ex="$(cat "$OUT/$c/$core.$r/exit" 2>/dev/null || echo none)"
            if [ "$ex" != 0 ]; then
                verdict=FAIL
                notes="$notes exit-$core=$ex"
            fi
            # Record `KNOWN ... XFAIL:` count in the summary without failing the scenario.
            xf="$(grep -c '^KNOWN .* XFAIL:' "$OUT/$c/$core.$r/out.dev" 2>/dev/null)"
            if [ "${xf:-0}" -gt 0 ]; then
                notes="$notes xfail-$core=$xf"
            fi
        done
        if [ "$mode" != DEV ]; then
            if ! diff -u <(view_trace "$mode" "$OUT/$c/c.$r/out.trace") \
                <(view_trace "$mode" "$OUT/$c/rust.$r/out.trace") \
                >"$OUT/$c/trace.$r.diff"; then
                verdict=FAIL
                notes="$notes trace"
            fi
        fi
        if [ "$lmode" != ignore ]; then
            if ! diff -u <(view_log "$lmode" "$OUT/$c/c.$r/out.log") \
                <(view_log "$lmode" "$OUT/$c/rust.$r/out.log") \
                >"$OUT/$c/log.$r.diff"; then
                verdict=FAIL
                notes="$notes log"
            fi
        fi
    done
    printf '%-24s %-8s %-8s %s%s\n' "$c" "$mode" "$lmode" "$verdict" "$notes" | tee -a "$SUMMARY"
    if [ "$verdict" != PASS ]; then
        FAILED=$((FAILED + 1))
    fi
done
echo "run.sh: $FAILED failed; results in $OUT" | tee -a "$SUMMARY"
[ "$FAILED" -eq 0 ]
