//! C ABI bridge implementation underpinning the `libzookeeper_mt` and `libzookeeper_st` drop-in
//! libraries.
//!
//! This crate provides the Rust implementation backing the legacy ZooKeeper C client compatibility
//! layer. The public C symbols reside within the thin C shim located at
//! `zookeeper-client-rust/c/shim`, which dispatches into internal `zkrs_*` entry points exposed by
//! this crate. The C declarations are synchronized via `shim/zkrs.h`, automatically generated by
//! `cbindgen` from `src/abi/types.rs` and annotated export signatures.
//!
//! A single unified Rust artifact caters to both multithreaded (`_mt`) and single threaded (`_st`)
//! client topologies. Client flavors are differentiated dynamically per session handle via
//! `zkrs_init_args.flavor`, allowing runtime dispatch to the appropriate driver loop. In default,
//! unfeatured configurations, TLS and SASL components are omitted entirely from compilation to
//! minimize binary footprint and attack surface.
//!
//! Unsafe operations are strictly segregated: all pointer dereferences, raw buffer writes, and C
//! memory manipulations are confined to `abi::raw` (and the synthetic test harness in
//! `abi::standin`). The crate globally enforces `#![deny(unsafe_code)]`, permitting `unsafe` only
//! for item-level `#[unsafe(no_mangle)]` export declarations and within the designated raw modules.
//! This invariant is actively verified by the `tests/unsafe_scope.rs` architectural boundary test.

#![deny(unsafe_code)]
#![cfg_attr(test, allow(clippy::disallowed_macros))]
// The generated test harness main has a large frame with no source span.
// Test builds allow it. Library builds keep the workspace deny.
#![cfg_attr(test, allow(clippy::large_stack_frames))]

// This compile-time guard rejects `tls` without a provider feature, mirroring the matching guard
// in `zk-driver`. `zk-ffi` has no guard against more than one provider: each provider feature
// here enables the `zk-driver` feature of the same name, and the `zk-driver` guard rejects more
// than one provider.
#[cfg(all(
    feature = "tls",
    not(any(
        feature = "tls-ring",
        feature = "tls-aws-lc-rs",
        feature = "tls-aws-lc-rs-fips"
    ))
))]
compile_error!(
    "zk-ffi feature `tls` needs exactly one provider feature: \
     `tls-ring`, `tls-aws-lc-rs` or `tls-aws-lc-rs-fips`"
);

mod abi;
