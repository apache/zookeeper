//! Outbound transmission queue and coordination channel for an individual client connection.
//!
//! Protocol response frames generated by the data tree model and actions scheduled by
//! fault injection rules are enqueued onto this channel while holding the cluster lock. The
//! connection worker thread drains the queue in FIFO order, writing byte slices, observing delays,
//! or closing the socket.

use std::collections::VecDeque;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Mutex, PoisonError};
use std::time::Duration;

/// Outbound action or payload scheduled for transmission to a connected client.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum Out {
    /// Serialized network payload segmented into discrete chunk writes to simulate packet
    /// fragmentation or partial socket writes.
    Bytes {
        /// Raw bytes representing one or more Jute protocol frames.
        data: Vec<u8>,
        /// Write slice lengths summing to `data.len()`.
        chunks: Vec<usize>,
    },
    /// Delay observed before processing subsequent items in the outbound queue.
    Pause(Duration),
    /// Instructs the connection worker to flush preceding items and close the socket.
    Close,
    /// Suspends inbound reads and outbound writes while keeping the TCP socket open.
    Stall,
}

/// Coordination channel between the cluster state machine and a connection worker thread.
#[derive(Debug, Default)]
pub(crate) struct ConnLink {
    queue: Mutex<VecDeque<Out>>,
    kill: AtomicBool,
}

impl ConnLink {
    /// Appends an outbound item to the back of the transmission queue.
    pub(crate) fn push(&self, item: Out) {
        self.queue
            .lock()
            .unwrap_or_else(PoisonError::into_inner)
            .push_back(item);
    }

    /// Removes and returns the next outbound item from the front of the transmission queue.
    pub(crate) fn pop(&self) -> Option<Out> {
        self.queue
            .lock()
            .unwrap_or_else(PoisonError::into_inner)
            .pop_front()
    }

    /// Signals the connection worker to close the socket immediately without draining the queue.
    pub(crate) fn kill(&self) {
        self.kill.store(true, Ordering::SeqCst);
    }

    /// Returns whether an immediate abort signal has been set on this connection.
    pub(crate) fn killed(&self) -> bool {
        self.kill.load(Ordering::SeqCst)
    }
}

/// Computes chunk lengths partitioning `len` bytes into slices of at most `size` bytes.
pub(crate) fn fixed_chunks(len: usize, size: usize) -> Vec<usize> {
    if size == 0 || len <= size {
        return vec![len];
    }
    let mut out = Vec::new();
    let mut left = len;
    while left > 0 {
        let n = left.min(size);
        out.push(n);
        left = left.saturating_sub(n);
    }
    out
}
